# -*- coding: utf-8 -*-
"""[공용 코어 · 압박×카테고리] 심판 판정표 — 74건을 묶는다. 호출 0.

    PC_ROOT=<...>/experiments/pressure_category python tools/verdicts.py

## 어떻게 가렸나 — 넷이 본다

1. **판독자** 4명이 조각을 읽고 판독물을 썼다
2. **대조자** 6명이 원문과 맞대 74건을 어긋남으로 짚었다(07·08 은 두 번)
3. **심판자** 16명이 그 74건을 조각 원문에 대고 가렸다 — 판독물 맞음 / 대조 맞음 /
   둘 다 틀림 / 못 가림. **대조자도 틀릴 수 있다**고 미리 일러 두었다
4. **기계**(이 자)가 심판자의 근거 인용을 원문과 글자 그대로 맞대 보고,
   셀 수 있는 것은 `COUNT2.json` 과 맞댄다

## 왜 이렇게까지 하나

같은 팩에서 **대조자가 맞는 판독을 틀렸다고 적은 적이 있다.**
심어 둔 정답 칸(「수첩2=3 이 20판 중 6~8판」)이 표본 통계였고,
그것을 믿은 대조가 09·10 의 맞는 셈에 어긋남을 매겼다.
그래서 판독물만 심판하지 않고 **대조와 정답 칸도 함께 심판한다.**

산출: VERDICTS2.md · VERDICTS2.json
"""
import json
import os
import re
import pathlib

H = pathlib.Path(__file__).resolve().parent.parent
조각들 = ["07_원칙_압박없음_보충", "08_원칙_반대로_보충",
        "09_가치_편들어_보충A", "10_가치_편들어_보충B"]

W = []


def w(s=""):
    W.append(s)


def 씻(s):
    return re.sub(r"[\s*`_]+", "", s or "")


def 판목록(s):
    """「13판 중 7판(04,05,06,…)」 꼴에서 번호를 뽑는다."""
    m = re.search(r"\(([\d,\s·]+)\)", s or "")
    if not m:
        return None
    나온 = re.findall(r"\d{1,2}", m.group(1))
    return sorted({x.zfill(2) for x in 나온}) or None


def main():
    R = json.loads((H / "_RULINGS2.json").read_text(encoding="utf-8"))
    M = {x["id"]: x for x in json.loads((H / "_MISMATCH2.json").read_text(encoding="utf-8"))}
    C = json.loads((H / "COUNT2.json").read_text(encoding="utf-8"))
    본문 = {s: 씻((H / f"{s}.md").read_text(encoding="utf-8")) for s in 조각들}

    # ── 기계 재검 ─────────────────────────────────────────────────
    인용맞 = 인용안 = 인용빔 = 0
    안맞은것 = []
    for r in R["rulings"]:
        q = r["evidence"]
        s = M[r["id"]]["조각"]
        if not q:
            인용빔 += 1
        elif 씻(q) in 본문[s]:
            인용맞 += 1
        else:
            인용안 += 1
            안맞은것.append((r["id"], q[:60]))

    # 셀 수 있는 것과 맞대기
    #
    # 정정 1 (2026-09-03) — 처음에는 truth 에서 **처음 걸린 낱말 하나**의 열만 대 봤다.
    # 그래서 「단/다만」을 묻는 판정 둘에 「다만」 열만 대어 **틀렸다고 잘못 찍었다.**
    # 심판이 맞았고 자가 틀렸다. 이 팩에서 같은 실수가 세 번째다
    # (정답 칸 → 대조 → 이 자). **검사의 범위를 주장의 범위에 맞춰야 한다.**
    # 이제 truth 안의 「…」 안 낱말을 **전부** 모아 합집합으로 맞댄다.
    낱말맞 = []
    for r in R["rulings"]:
        s = M[r["id"]]["조각"]
        t = r["truth"]
        인용된 = set()
        for 덩이 in re.findall(r"「([^」]+)」", t) + re.findall(r"`([^`]+)`", t):
            for 조각말 in re.split(r"[/·]", 덩이):
                조각말 = 조각말.strip()
                for 낱 in C[s]["낱말"]:
                    if 조각말 == 낱 or 조각말 == 낱.rstrip(",:"):
                        인용된.add(낱)
        if not 인용된:
            continue
        뽑 = 판목록(t)
        if not 뽑:
            continue
        합 = sorted({p for 낱 in 인용된 for p in C[s]["낱말"][낱]})
        if len(인용된) == 1:
            낱 = next(iter(인용된))
            판정 = "일치" if 뽑 == C[s]["낱말"][낱] else "어긋남"
        else:
            # 정정 2 — 낱말이 여럿 인용된 주장은 **어느 것이 주장 대상인지 자가 못 가린다.**
            # 「단/다만」은 둘 다 대상이었고, 「이유: … 03(「핵심:」)에는 없고」는
            # 「이유:」만 대상이었다. 합집합으로 재면 앞은 맞고 뒤는 틀린다.
            # 자동으로 편을 들지 않고 **못 맞댐**으로 두고 두 값을 나란히 적는다.
            판정 = "못 맞댐"
        낱말맞.append((r["id"], " · ".join(sorted(인용된)), 판정, 뽑, 합))

    w("# 심판 판정표 — 2차 판독물 어긋남 74건 (2026-09-03)")
    w("")
    w("> 기계 산출물. `tools/verdicts.py` 가 쓴다. 손으로 고치지 마라.")
    w("> 판독자 4 → 대조자 6 → 심판자 16 → 기계 재검. **넷이 봤다.**")
    w("")
    w("같은 팩에서 **대조자가 맞는 판독을 틀렸다고 적은 적이 있어**(§3),")
    w("판독물만이 아니라 대조와 정답 칸도 함께 심판했다.")

    # ── 1. 요약 ──────────────────────────────────────────────────
    w("\n## 1. 판정\n")
    w("| 판정 | 건수 |")
    w("|---|---:|")
    for k, v in sorted(R["tally"].items(), key=lambda x: -x[1]):
        w(f"| {k} | {v} |")
    w(f"| **합** | **{R['ruled']}** |")
    w("")
    w("**판독물 맞음이 0 이다.** 대조가 짚은 자리는 거의 다 실제 오류였다.")
    w("다만 이 74건은 **대조가 「틀렸다」고 고른 것만** 모은 것이라,")
    w("판독물 전체의 정확도를 말하지 않는다 — 맞은 자리는 애초에 여기 안 들어온다.")

    # ── 2. 기계 재검 ─────────────────────────────────────────────
    w("\n## 2. 기계가 다시 본 것\n")
    w(f"- 심판자의 근거 인용이 조각에 **글자 그대로 있음 {인용맞} · 없음 {인용안} · "
      f"근거 비움 {인용빔}**")
    if 안맞은것:
        for i, q in 안맞은것:
            w(f"  - 못 찾음: {i} 「{q}」")
    else:
        w("  (근거를 비운 둘은 판독물 내부 셈이라 조각으로는 못 가리는 항목이다)")
    w("")
    if 낱말맞:
        맞 = sum(1 for x in 낱말맞 if x[2] == "일치")
        못 = sum(1 for x in 낱말맞 if x[2] == "못 맞댐")
        w(f"- 낱말 셈이 걸린 판정 {len(낱말맞)}건을 `COUNT2.json` 과 맞댐 — "
          f"**일치 {맞} · 어긋남 {len(낱말맞) - 맞 - 못} · 못 맞댐 {못}**")
        w("")
        w("| 어긋남 | 인용된 낱말 | 심판이 적은 판 | 기계(합집합) | 판정 |")
        w("|---|---|---|---|---|")
        for i, 낱, 판정, 뽑, 실 in 낱말맞:
            표 = {"일치": "○", "어긋남": "**×**", "못 맞댐": "— 못 맞댐"}[판정]
            w(f"| {i} | `{낱}` | {', '.join(뽑)} | {', '.join(실)} | {표} |")
        if 못:
            w("")
            w("**「못 맞댐」은 자가 주장의 범위를 못 가린 것이다.** 낱말이 둘 이상 인용된 주장에서")
            w("어느 것이 대상인지 자동으로 못 안다 — 「단/다만」은 둘 다 대상이었고,")
            w("「이유: … 03(「핵심:」)에는 없고」는 「이유:」만 대상이었다.")
            w("합집합으로 재면 앞은 맞고 뒤는 틀린다. **자가 편을 들지 않게 비워 뒀다.**")

    # ── 3. 정답 칸 ───────────────────────────────────────────────
    w("\n## 3. 정답 칸에서 온 어긋남 — 여기서는 판독물이 맞다\n")
    w("위 74건과 **별개**로, 대조가 심어 둔 정답 칸에서 2건을 「어긋남」으로 표시했다.")
    w("그 칸은 「gpt 조각에서 수첩2=3 이 20판 중 6~8판」이었다.")
    w("")
    w("| | 판독물이 적은 판 | 기계 실측 | |")
    w("|---|---|---|---|")
    for s, 표 in (("09_가치_편들어_보충A", "12, 19"),
                  ("10_가치_편들어_보충B", "07, 08, 12, 17, 20")):
        실 = C[s]["수첩2_3"]
        w(f"| {s[:2]} | {표} | {', '.join(실)} | {'**판독물 맞음**' if 표.replace(' ', '') == ','.join(실) else '다름'} |")
    w("")
    w("모집단은 A/B C1 에서 48/240 = 20%, **20판이면 4판**이다.")
    w("「6~8판」은 1차 A/B 조각 셋(6·6·8)만 보고 굳힌 값이고 신념·올세트는 2~5였다.")
    w("**표본 통계를 정답으로 굳히면 맞는 판독을 틀렸다고 적게 된다.**")

    # ── 4. 전건 ──────────────────────────────────────────────────
    w("\n## 4. 전건\n")
    for s in 조각들:
        묶 = [r for r in R["rulings"] if M[r["id"]]["조각"] == s]
        if not 묶:
            continue
        w(f"\n### {s} — {len(묶)}건\n")
        for r in 묶:
            m = M[r["id"]]
            w(f"**{r['id']}** · {r['verdict']} · 대조 {m['대조'][-1]}차")
            w("")
            w(f"- 판독물: {m['주장'][:150]}")
            w(f"- **맞는 값**: {r['truth']}")
            if r["evidence"]:
                w(f"- 근거: 「{r['evidence'][:150]}」")
            w("")

    # ── 5. 쓰는 법 ───────────────────────────────────────────────
    w("\n## 5. 그래서 2차 판독물을 어떻게 쓰나\n")
    w("- **판독물은 안 고쳤다** — 증거물이다. 이 표가 정정본이다.")
    w("- **세는 말은 이 표를 거쳐 쓴다.** 07·08 은 29건씩 걸렸다.")
    w("- **뼈대·채움 갈래 같은 서술은 그대로 쓸 수 있다** — 심판이 「못 가림」으로 둔 것은")
    w("  판독자의 해석이라 원문으로 편을 못 가리는 자리다.")
    w("- 이 74건은 **대조가 고른 것만** 모은 것이다. 판독물의 정확도가 아니다.")

    (H / "VERDICTS2.md").write_text("\n".join(W) + "\n", encoding="utf-8")
    (H / "VERDICTS2.json").write_text(json.dumps(dict(
        판정=R["tally"], 건수=R["ruled"],
        기계재검=dict(인용맞=인용맞, 인용안=인용안, 인용빔=인용빔,
                  낱말=[dict(id=i, 낱말=n, 맞음=ok, 심판=뽑, 기계=실)
                       for i, n, ok, 뽑, 실 in 낱말맞]),
        판정들=R["rulings"]), ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"→ VERDICTS2.md · VERDICTS2.json")
    print(f"  판정 {R['ruled']}건 {R['tally']}")
    print(f"  근거 인용 {인용맞}/{인용맞 + 인용안 + 인용빔} 원문 일치 · 낱말 대조 "
          f"{sum(1 for x in 낱말맞 if x[2])}/{len(낱말맞)}")


if __name__ == "__main__":
    main()
